class I18nEngine {
    constructor() {
        this.currentLang = localStorage.getItem('mib_lang') || 'ar';
        this.init();
    }

    init() {
        this.applyLanguage(this.currentLang);
    }

    setLanguage(lang) {
        if (lang !== 'ar' && lang !== 'en') return;
        this.currentLang = lang;
        localStorage.setItem('mib_lang', lang);
        this.applyLanguage(lang);
    }

    toggleLanguage() {
        const nextLang = this.currentLang === 'ar' ? 'en' : 'ar';
        this.setLanguage(nextLang);
    }

    applyLanguage(lang) {
        const isRTL = lang === 'ar';
        document.documentElement.lang = lang;
        document.documentElement.dir = isRTL ? 'rtl' : 'ltr';

        if (isRTL) {
            document.body.classList.add('rtl-layout');
            document.body.classList.remove('ltr-layout');
        } else {
            document.body.classList.add('ltr-layout');
            document.body.classList.remove('rtl-layout');
        }

        const dict = translations[lang] || translations.ar;

        // ترجمة العناصر بناءً على data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                el.textContent = dict[key];
            }
        });

        // ترجمة النصوص التلميحية placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) {
                el.placeholder = dict[key];
            }
        });

        // تحديث زر تبديل اللغة في القائمة
        const langToggleLabel = document.getElementById('langToggleLabel');
        if (langToggleLabel) {
            langToggleLabel.textContent = isRTL ? 'English' : 'العربية';
        }

        window.dispatchEvent(new CustomEvent('mind:lang:changed', { detail: { lang, isRTL } }));
    }

    t(key) {
        const dict = translations[this.currentLang] || translations.ar;
        return dict[key] || key;
    }
}

// إنشاء الكائن العام
window.MindI18n = new I18nEngine();
